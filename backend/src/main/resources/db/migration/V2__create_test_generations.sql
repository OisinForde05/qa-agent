CREATE TABLE test_generations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requirement_id BIGINT NOT NULL REFERENCES requirements(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    model_name VARCHAR(255) NOT NULL
);

CREATE INDEX idx_generations_requirement
    ON test_generations(requirement_id);

CREATE TABLE generation_issues (
    generation_id BIGINT NOT NULL
        REFERENCES test_generations(id) ON DELETE CASCADE,
    issue_position INTEGER NOT NULL,
    issue_text TEXT NOT NULL,
    PRIMARY KEY (generation_id, issue_position)
);

CREATE TABLE generated_test_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generation_id BIGINT NOT NULL
        REFERENCES test_generations(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    expected_result TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    CONSTRAINT chk_test_case_status
        CHECK (status IN ('DRAFT', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_cases_generation
    ON generated_test_cases(generation_id);

CREATE TABLE test_case_preconditions (
    test_case_id BIGINT NOT NULL
        REFERENCES generated_test_cases(id) ON DELETE CASCADE,
    item_position INTEGER NOT NULL,
    item_text TEXT NOT NULL,
    PRIMARY KEY (test_case_id, item_position)
);

CREATE TABLE test_case_steps (
    test_case_id BIGINT NOT NULL
        REFERENCES generated_test_cases(id) ON DELETE CASCADE,
    item_position INTEGER NOT NULL,
    item_text TEXT NOT NULL,
    PRIMARY KEY (test_case_id, item_position)
);